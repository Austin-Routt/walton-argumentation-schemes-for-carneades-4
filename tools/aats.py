#!/usr/bin/env python3
"""Practical reasoning over action-based alternating transition systems (AATS).

Atkinson and Bench-Capon (2007), "Practical reasoning as presumptive
argumentation using action based alternating transition systems", Artificial
Intelligence 171, pp. 855-874. Section 4 defines the AATS extended with values,
section 5 the argument scheme AS2 and the seventeen critical questions on it,
sections 6 and 7 the farmer and the trains. This module

  * reads and validates models (tools/aats_models/*.yml), one AATS per choice
    point ("situation"), against the definitions of pp. 860-861;
  * builds the AS2 arguments of a situation, positive and negative (p. 859),
    with the facts that let Carneades build the same arguments from the
    library records practical_reasoning_as2 and practical_reasoning_as2_demotion;
  * answers the critical questions: the problem-formulation and epistemic ones
    (CQ1-CQ4, CQ12-CQ16) for a claimed argument, and the choice-of-action ones
    (CQ5-CQ11, CQ17) as objections the model supports (p. 862);
  * implements the comparison contract value-based-choice (docs/contracts.md,
    contract 8): which of an agent's actions an audience's value order selects.

Usage:
  python3 tools/aats.py check [MODEL...]          validate models, decisions and the generated cases
  python3 tools/aats.py cases [MODEL...] [--write] the Carneades case file (tools/vv/cases/practical_as2.yml)
  python3 tools/aats.py decide MODEL [SITUATION] [--audience NAME|v1,v2,...]
  python3 tools/aats.py arguments MODEL SITUATION  arguments and objections, as JSON
Requires PyYAML.
"""
import argparse
import itertools
import json
import sys
from collections import namedtuple
from pathlib import Path

import yaml

SCHEMA = "walton-aats/v1"
ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "tools" / "aats_models"
CASES = ROOT / "tools" / "vv" / "cases" / "practical_as2.yml"
POSITIVE, NEGATIVE = "practical_reasoning_as2", "practical_reasoning_as2_demotion"
CASE_HEADER = ("# Generated by tools/aats.py from tools/aats_models/*.yml. Do not edit: change a model\n"
               "# and run `python3 tools/aats.py cases --write`. Each case states one situation's AATS as\n"
               "# facts and lists every AS2 argument Carneades must build from them, no more and no fewer\n"
               "# (exact_schemes), with the labels of the agent's options under the engine's own weighing\n"
               "# (no audience: a con argument of weight 1 blocks a pro argument of weight 1). Which option an\n"
               "# audience chooses is the comparison contract's (tools/aats.py decide), not the engine's.\n")

TOP_KEYS = {"schema", "name", "source", "agents", "joint_actions", "audiences", "situations", "common"}
SITUATION_KEYS = {"name", "source", "agent", "values", "initial", "states", "transitions", "assurances",
                  "decisions", "preconditions"}
TRANSITION_KEYS = {"from", "by", "to", "promotes", "demotes"}

Argument = namedtuple("Argument", "sign agent action joint state result goal value")
Effect = namedtuple("Effect", "sign value goal")


class ModelError(Exception):
    pass


def _atom(x, what):
    if not isinstance(x, str) or not x or not (x[0].islower() and x.replace("_", "a").isalnum()):
        raise ModelError(f"{what} {x!r} is not an atom (lower case letter, then letters, digits or _)")
    return x


class Situation:
    """One AATS S = <Q, q0, Ag, Ac_1..Ac_n, Av_1..Av_n, rho, tau, Phi, pi, delta>
    (pp. 860-861), with the deliberating agent and the joint actions its
    assurances exclude (the answers to CQ17 the agent accepts, p. 859)."""

    def __init__(self, model, raw):
        self.model = model
        unknown = set(raw) - SITUATION_KEYS
        if unknown:
            raise ModelError(f"unknown situation keys {sorted(unknown)}")
        self.name = raw.get("name")
        self.source = raw.get("source", "")
        where = f"{model.name}/{self.name}"
        if not self.name or not self.source:
            raise ModelError(f"{where}: a situation needs a name and a source")
        self.agents = model.agents                                   # Ag, Ac_i
        self.joint = model.joint                                     # named elements of J_Ag
        self.values = {i: list(vs) for i, vs in (raw.get("values") or {}).items()}   # Av_i
        self.states = {q: frozenset(p) for q, p in (raw.get("states") or {}).items()}  # Q, pi
        self.initial = raw.get("initial")                            # q0
        self.agent = raw.get("agent")
        self.tau, self.effects = {}, {}
        for t in raw.get("transitions") or []:
            unknown = set(t) - TRANSITION_KEYS
            if unknown:
                raise ModelError(f"{where}: unknown transition keys {sorted(unknown)}")
            key = (t.get("from"), t.get("by"))
            if key in self.tau:
                raise ModelError(f"{where}: tau({key[0]}, {key[1]}) is given twice: tau is a function")
            self.tau[key] = t.get("to")
            effs = []
            for sign, field in (("+", "promotes"), ("-", "demotes")):
                for v, goals in (t.get(field) or {}).items():
                    if not isinstance(goals, list) or not goals:
                        raise ModelError(f"{where}: {field} {v} on {key} needs a list of goals")
                    for g in goals:
                        effs.append(Effect(sign, v, g))
            self.effects[key] = effs
        self.assurances = set(raw.get("assurances") or [])
        self.decisions = raw.get("decisions") or []
        rho = raw.get("preconditions")
        if rho is None:
            # the least precondition function that agrees with tau: an action
            # can be performed where a transition uses it
            rho = {}
            for (q, j) in self.tau:
                for a in (self.joint.get(j) or {}).values():
                    rho.setdefault(a, set()).add(q)
        self.rho = {a: set(qs) for a, qs in rho.items()}
        self.problems = self._validate()
        if self.problems:
            raise ModelError(f"{where}: " + "; ".join(self.problems))

    # -- the definitions of pp. 860-861 ------------------------------------
    def _validate(self):
        p = []
        if not self.states:
            p.append("Q is empty")
        for q, props in self.states.items():
            try:
                _atom(q, "state")
                for x in props:
                    _atom(x, "proposition")
            except ModelError as e:
                p.append(str(e))
        if self.initial not in self.states:
            p.append(f"the initial state {self.initial!r} is not in Q")
        if self.agent not in self.agents:
            p.append(f"the deliberating agent {self.agent!r} is not in Ag")
        if set(self.values) != set(self.agents):
            p.append("every agent needs its set of values Av_i, and only agents have one")
        for i, vs in self.values.items():
            if not vs or len(set(vs)) != len(vs):
                p.append(f"Av_{i} must be a non-empty set")
            for v in vs:
                try:
                    _atom(v, "value")
                except ModelError as e:
                    p.append(str(e))
        V = self.V()
        dup = [s for s in self.states.values()]
        if len(set(dup)) != len(dup):
            p.append("two states have the same interpretation pi(q); states are told apart by what holds in them")
        for (q, j), q1 in self.tau.items():
            if q not in self.states or q1 not in self.states:
                p.append(f"tau({q}, {j}) = {q1}: both states must be in Q")
                continue
            if j not in self.joint:
                p.append(f"tau({q}, {j}): {j} is not a joint action")
                continue
            for a in self.joint[j].values():
                if q not in self.rho.get(a, set()):
                    p.append(f"tau({q}, {j}) is defined, but {a} cannot be performed in {q} (rho)")
            changed = self.states[q] ^ self.states[q1]
            seen = set()
            for e in self.effects[(q, j)]:
                if e.value not in V:
                    p.append(f"tau({q}, {j}): {e.value} is not a value of any agent")
                if e.goal not in changed:
                    p.append(f"tau({q}, {j}): the goal {e.goal} of {e.sign}{e.value} does not change between {q} and {q1}")
                if (e.sign, e.value, e.goal) in seen:
                    p.append(f"tau({q}, {j}): {e.sign}{e.value} by {e.goal} is given twice")
                seen.add((e.sign, e.value, e.goal))
        for a, qs in self.rho.items():
            if not any(a in acts for acts in self.agents.values()):
                p.append(f"rho names {a}, which is no agent's action")
            if not qs <= set(self.states):
                p.append(f"rho({a}) names states outside Q")
        for j in self.assurances:
            if (self.initial, j) not in self.tau:
                p.append(f"an assurance excludes {j}, which cannot be performed in {self.initial}")
        if self.agent in self.agents and self.initial in self.states:
            # an assurance is about the other agents' choices: it cannot take
            # away an action of the deliberating agent
            mine = {self.joint[j][self.agent] for (q, j) in self.tau if q == self.initial and j in self.joint}
            left = {self.joint[j][self.agent] for (q, j) in self.tau
                    if q == self.initial and j in self.joint and j not in self.assurances}
            if mine != left:
                p.append(f"the assurances exclude every joint action of {sorted(mine - left)}")
        if self.agent in self.agents and not self.options():
            p.append(f"{self.agent} has no action in {self.initial}")
        return p

    def V(self):
        return {v for vs in self.values.values() for v in vs}

    def Phi(self):
        return set().union(*self.states.values()) if self.states else set()

    def delta(self, qx, qy, v):
        """delta(qx, qy, v) of p. 861 for a transition of tau: '+', '-' or '='.
        A transition the figures label both +v and -v (Fig. 6) gives '+-'."""
        signs = set()
        for (q, j), q1 in self.tau.items():
            if q == qx and q1 == qy:
                signs |= {e.sign for e in self.effects[(q, j)] if e.value == v}
        return "".join(sorted(signs, reverse=True)) or "="

    def possible(self, q=None):
        """The joint actions that can be performed in q (by default the current
        state) and that no assurance excludes."""
        q = self.initial if q is None else q
        return [j for (x, j) in self.tau if x == q and (q != self.initial or j not in self.assurances)]

    def options(self, agent=None):
        agent = agent or self.agent
        return sorted({self.joint[j][agent] for j in self.possible()})

    # -- AS2 arguments (p. 861) and the negative version (p. 859) -------------
    def arguments(self):
        """Every AS2 argument of the deliberating agent in the current state:
        one per possible joint action, value of the agent, and goal whose
        change promotes (sign +) or demotes (sign -) that value."""
        out = []
        q0, i = self.initial, self.agent
        for j in self.possible():
            for e in self.effects[(q0, j)]:
                if e.value in self.values[i]:
                    out.append(Argument(e.sign, i, self.joint[j][i], j, q0, self.tau[(q0, j)], e.goal, e.value))
        return sorted(out)

    def deviations(self, arg):
        """CQ17 (p. 862): the joint actions jm with jm_i = jn_i, jm != jn and
        tau(qx, jm) != tau(qx, jn) that the agent cannot exclude, each with
        whether the argument's value is still promoted there (the answer to
        CQ17 of Obj2bi, p. 865, and of the eastbound train in q7, p. 871)."""
        out = []
        for jm in self.possible():
            if jm != arg.joint and self.joint[jm][arg.agent] == arg.action and self.tau[(arg.state, jm)] != arg.result:
                promoted = any(e.sign == "+" and e.value == arg.value for e in self.effects[(arg.state, jm)])
                out.append((jm, promoted))
        return out

    def cq17_unanswered(self, arg):
        return arg.sign == "+" and any(not promoted for _, promoted in self.deviations(arg))

    def objections(self, arg):
        """The choice-of-action critical questions (CQ5-CQ11) and CQ17, as
        defined on the AATS on p. 862, that the model answers unfavourably for
        a positive argument."""
        qx, jn, qy, pa, vu = arg.state, arg.joint, arg.result, arg.goal, arg.value
        out = []
        others = [jm for jm in self.possible() if jm != jn]
        for jm in others:
            qz = self.tau[(qx, jm)]
            if qz == qy:
                out.append({"cq": 5, "joint": jm, "result": qz})
            if pa in self.states[qx] ^ self.states[qz]:
                out.append({"cq": 6, "joint": jm, "result": qz, "goal": pa})
            for e in self.effects[(qx, jm)]:
                if e.sign == "+" and e.value == vu:
                    out.append({"cq": 7, "joint": jm, "result": qz, "goal": e.goal, "value": vu})
                if e.sign == "+" and e.value != vu:
                    out.append({"cq": 11, "joint": jm, "result": qz, "goal": e.goal, "value": e.value})
        for e in self.effects[(qx, jn)]:
            if e.sign == "-" and e.value == vu and e.goal != pa:
                out.append({"cq": 8, "goal": e.goal, "value": vu})
            if e.sign == "-" and e.value != vu:
                out.append({"cq": 9, "goal": e.goal, "value": e.value})
            if e.sign == "+" and e.value != vu:
                out.append({"cq": 10, "goal": e.goal, "value": e.value})
        for jm, promoted in self.deviations(arg):
            out.append({"cq": 17, "joint": jm, "result": self.tau[(qx, jm)], "answered": promoted,
                        "demotes": sorted({e.value for e in self.effects[(qx, jm)] if e.sign == "-"})})
        return out

    # -- claimed arguments: problem formulation and epistemic stage (p. 862) --
    def _state(self, s):
        if isinstance(s, str):
            return s if s in self.states else None
        props = frozenset(s or [])
        return next((q for q, p in self.states.items() if p == props), None)

    def claim_problems(self, claim):
        """The critical questions answered unfavourably for an argument that
        another agent claims, with its own formulation of the problem: a
        state (an id of Q, or the list of what holds in it), a joint action
        (a name, or a mapping agent -> action), the agent and its action, the
        resulting state, the goal and the value (pp. 862 and 864)."""
        cqs = set()
        qx, qy = self._state(claim.get("state")), self._state(claim.get("result"))
        i, a = claim.get("agent"), claim.get("action")
        j = claim.get("joint")
        if isinstance(j, dict):
            j = next((n for n, acts in self.joint.items() if acts == j), None)
        elif j not in self.joint:
            j = None
        pa, vu = claim.get("goal"), claim.get("value")
        if qx is None:
            cqs.add(12)                                     # qx not in Q
        if j is None or (i is not None and self.joint[j].get(i) != a):
            cqs.add(13)                                     # jn not in J_Ag (with jn_i = alpha_i)
        if qy is None:
            cqs.add(14)                                     # tau(qx, jn) not in Q
        if pa not in self.Phi():
            cqs.add(15)                                     # pa in pi(q) for no q in Q
        if vu not in self.V():
            cqs.add(16)                                     # vu not in V
        if qx is not None and (qx != self.initial or (a is not None and qx not in self.rho.get(a, set()))):
            cqs.add(1)                                      # not the current state, or alpha_i's precondition fails
        if qx is not None and j is not None and qy is not None and self.tau.get((qx, j)) != qy:
            cqs.add(2)                                      # tau(qx, jn) is not qy
        if qx is not None and qy is not None and pa not in (self.states[qx] ^ self.states[qy]):
            cqs.add(3)                                      # pa does not change between qx and qy
        if qx is not None and qy is not None and j is not None and self.tau.get((qx, j)) == qy \
                and "+" not in self.delta(qx, qy, vu):
            cqs.add(4)                                      # delta(qx, qy, vu) is not +
        return sorted(cqs)

    # -- the comparison contract value-based-choice ---------------------------
    def scores(self, audience):
        """For each option alpha of the deliberating agent and each value v of
        the audience that is one of its values: the least, over the joint
        actions with jn_i = alpha that the agent cannot exclude, of the number
        of goals promoting v minus the number demoting it."""
        vals = [v for v in audience if v in self.values[self.agent]]
        out = {}
        for a in self.options():
            outcomes = [j for j in self.possible() if self.joint[j][self.agent] == a]
            out[a] = tuple(min(sum((e.sign == "+") - (e.sign == "-") for e in self.effects[(self.initial, j)]
                                   if e.value == v) for j in outcomes) for v in vals)
        return vals, out

    def decide(self, audience):
        vals, sc = self.scores(audience)
        best = max(sc.values())
        return sorted(a for a, s in sc.items() if s == best)

    # -- Carneades facts ------------------------------------------------------
    def facts(self):
        f = [f"current_state({self.initial})"]
        f += [f"model_state({q})" for q in sorted(self.states)]
        used = sorted({j for (_, j) in self.tau})
        for j in used:
            for i, a in sorted(self.joint[j].items()):
                f.append(f"joint_action_part({j},{i},{a})")
        for a in sorted(self.rho):
            f += [f"precondition_holds({a},{q})" for q in sorted(self.rho[a])]
        f += [f"possible_joint_action({j},{self.initial})" for j in sorted(self.possible())]
        for (q, j), q1 in sorted(self.tau.items()):
            f.append(f"transition({q},{j},{q1})")
            f += [f"proposition_changes({p},{q},{q1})" for p in sorted(self.states[q] ^ self.states[q1])]
        f += [f"proposition_realizable({p})" for p in sorted(self.Phi())]
        f += [f"agent_value({self.agent},{v})" for v in self.values[self.agent]]
        for (q, j), q1 in sorted(self.tau.items()):
            for e in self.effects[(q, j)]:
                pred = "transition_promotes" if e.sign == "+" else "transition_demotes"
                fact = f"{pred}({q},{q1},{e.goal},{e.value})"
                if fact not in f:
                    f.append(fact)
        for arg in self.arguments():
            if self.cq17_unanswered(arg):
                fact = f"others_may_prevent({arg.state},{arg.joint},{arg.agent},{arg.value})"
                if fact not in f:
                    f.append(fact)
        return f


def argument_id(arg):
    scheme = POSITIVE if arg.sign == "+" else NEGATIVE
    return f"{scheme}({arg.agent},{arg.action},{arg.joint},{arg.state},{arg.result},{arg.goal},{arg.value})"


def engine_labels(sit):
    """The labels Carneades gives should_perform(i, alpha) and its negation
    under its own weighing: each built argument weighs 1 unless undercut;
    within the issue {S, not S} a position is in when its best argument
    outweighs the other's, and otherwise both are out (caes.Issue.Resolve)."""
    out = {}
    for a in sit.options():
        args = [x for x in sit.arguments() if x.action == a]
        built_pro = any(x.sign == "+" for x in args)
        pro = any(x.sign == "+" and not sit.cq17_unanswered(x) for x in args)
        con = any(x.sign == "-" for x in args)
        s = f"should_perform({sit.agent},{a})"
        # a statement no argument concludes is not in the graph at all
        if built_pro:
            out[s] = "in" if pro and not con else "out"
        if con:
            out["¬" + s] = "in" if not pro else "out"
    return out


class Model:
    def __init__(self, path):
        self.path = Path(path)
        doc = yaml.safe_load(self.path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict) or doc.get("schema") != SCHEMA:
            raise ModelError(f"{path}: schema must be {SCHEMA}")
        unknown = set(doc) - TOP_KEYS
        if unknown:
            raise ModelError(f"{path}: unknown keys {sorted(unknown)}")
        self.name, self.source = doc.get("name"), doc.get("source")
        if not self.name or not self.source:
            raise ModelError(f"{path}: a model needs a name and a source")
        self.agents = {i: list(acts) for i, acts in (doc.get("agents") or {}).items()}
        if not self.agents:
            raise ModelError(f"{path}: Ag is empty")
        every = [a for acts in self.agents.values() for a in acts]
        for i, acts in self.agents.items():
            _atom(i, "agent")
            if not acts:
                raise ModelError(f"{path}: Ac_{i} is empty")
            for a in acts:
                _atom(a, "action")
        if len(set(every)) != len(every):
            raise ModelError(f"{path}: the agents' action sets must be pairwise disjoint")
        self.joint = {}
        for j, acts in (doc.get("joint_actions") or {}).items():
            _atom(j, "joint action")
            if set(acts) != set(self.agents) or any(acts[i] not in self.agents[i] for i in acts):
                raise ModelError(f"{path}: joint action {j} must give each agent exactly one of its own actions")
            self.joint[j] = dict(acts)
        tuples = [tuple(sorted(a.items())) for a in self.joint.values()]
        if len(set(tuples)) != len(tuples):
            raise ModelError(f"{path}: two joint actions name the same tuple of actions")
        self.audiences = {n: list(o) for n, o in (doc.get("audiences") or {}).items()}
        for n, order in self.audiences.items():
            if len(set(order)) != len(order):
                raise ModelError(f"{path}: audience {n} must be a strict order")
        self.situations = [Situation(self, raw) for raw in doc.get("situations") or []]
        names = [s.name for s in self.situations]
        if not names or len(set(names)) != len(names):
            raise ModelError(f"{path}: situations need distinct names")

    def audience(self, spec):
        if spec in self.audiences:
            return self.audiences[spec]
        return [v for v in spec.split(",") if v]

    def situation(self, name):
        for s in self.situations:
            if s.name == name:
                return s
        raise ModelError(f"{self.path}: no situation {name}")


def model_paths(paths=None):
    return [Path(p) for p in paths] if paths else sorted(MODELS.glob("*.yml"))


def decision_problems(model):
    out = []
    for sit in model.situations:
        for d in sit.decisions:
            if set(d) - {"audience", "choose", "source"} or not d.get("source"):
                out.append(f"{model.name}/{sit.name}: a decision has audience, choose and source")
                continue
            got = sit.decide(model.audience(d["audience"]))
            if got != sorted(d["choose"]):
                out.append(f"{model.name}/{sit.name}: audience {d['audience']} chooses {got}, the paper {sorted(d['choose'])}")
    return out


def build_cases(models):
    cases = []
    for m in models:
        for sit in m.situations:
            args = [argument_id(a) for a in sit.arguments()]
            labels = engine_labels(sit)
            cases.append({
                "name": f"practical_reasoning_as2/{m.name}-{sit.name}",
                "source": f"{m.source}; {sit.source}",
                "assumptions": sit.facts(),
                "arguments": args,
                "exact_schemes": [POSITIVE, NEGATIVE],
                "in": sorted(s for s, l in labels.items() if l == "in"),
                "out": sorted(s for s, l in labels.items() if l == "out"),
            })
    return CASE_HEADER + yaml.safe_dump({"cases": cases}, sort_keys=False, allow_unicode=True, width=1000)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("models", nargs="*")
    c = sub.add_parser("cases")
    c.add_argument("models", nargs="*")
    c.add_argument("--write", action="store_true")
    c = sub.add_parser("decide")
    c.add_argument("model")
    c.add_argument("situation", nargs="?")
    c.add_argument("--audience")
    c = sub.add_parser("arguments")
    c.add_argument("model")
    c.add_argument("situation")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "check":
            models = [Model(p) for p in model_paths(a.models)]
            probs = [p for m in models for p in decision_problems(m)]
            if not a.models and CASES.read_text(encoding="utf-8") != build_cases(models):
                probs.append(f"{CASES.relative_to(ROOT)} is stale: run python3 tools/aats.py cases --write")
            for p in probs:
                print("FAIL", p)
            n = sum(len(s.decisions) for m in models for s in m.situations)
            print(f"{len(models)} model(s), {sum(len(m.situations) for m in models)} situation(s), "
                  f"{n} decision(s) checked: {'FAIL' if probs else 'OK'}")
            return 1 if probs else 0
        if a.cmd == "cases":
            text = build_cases([Model(p) for p in model_paths(a.models)])
            if a.write:
                CASES.write_text(text, encoding="utf-8")
                print(f"wrote {CASES.relative_to(ROOT)}")
            else:
                sys.stdout.write(text)
            return 0
        m = Model(a.model)
        if a.cmd == "decide":
            sits = [m.situation(a.situation)] if a.situation else m.situations
            auds = [a.audience] if a.audience else sorted(m.audiences)
            for s in sits:
                for au in auds:
                    vals, sc = s.scores(m.audience(au))
                    print(json.dumps({"situation": s.name, "audience": au, "values": vals,
                                      "scores": sc, "choose": s.decide(m.audience(au))}))
            return 0
        s = m.situation(a.situation)
        print(json.dumps([{"argument": argument_id(x), "cq17_unanswered": s.cq17_unanswered(x),
                           "objections": s.objections(x) if x.sign == "+" else []} for x in s.arguments()], indent=1))
        return 0
    except ModelError as e:
        print("error:", e, file=sys.stderr)
        return 2


