#!/usr/bin/env python3
"""Start an argument graph from the library: the schemes you name, the language
templates they use and the issue schemes, copied verbatim from walton.yml.

Usage:  python3 tools/graph_from_library.py SCHEME [SCHEME ...] [--library FILE] [--title TITLE]

Carneades 4 has no include mechanism: a graph file has to carry the language
and the schemes it uses (PLAN.md, Phase 6). The output is such a file, with
the parts that describe a case left for you to write: assumptions, questioned
statements, issues and the labels you expect. See docs/using.md.
Requires PyYAML.
"""
import json
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_category_files import read_master, templates_used  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CASE = """
# --- the case ----------------------------------------------------------------
# Write the facts of the case below, one term per line (see docs/using.md):
#
# assumptions:            # what holds; premises and answers to questions
#   - expert(smith,law)
# questioned:             # assumptions of a scheme called into question
#   - credible(smith)
# issues:                 # optional: positions weighed under a proof standard
#   i1:
#     positions: [liable(acme), ¬liable(acme)]
#     standard: PE
# tests:                  # optional: the labels you expect
#   in: [liable(acme)]
"""


def graph(ids, library, title=None):
    ids = list(dict.fromkeys(ids))                                   # each scheme once
    templates, blocks, issues = read_master(library)
    meta = yaml.safe_load(open(library, encoding="utf-8")).get("meta") or {}
    unknown = [s for s in ids if s not in blocks]
    if unknown:
        raise SystemExit(f"{os.path.basename(library)} has no scheme {', '.join(unknown)}")
    used = []
    for sid in ids:
        for k in templates_used(blocks[sid]):
            if k not in used:
                used.append(k)
    missing = [k for k in used if k not in templates]
    if missing:
        raise SystemExit(f"{os.path.basename(library)} has no template for {missing}")
    version = meta.get("version")
    out = [f"# Generated by tools/graph_from_library.py from {os.path.basename(library)}"
           + (f" (library {version})" if version else "") + f": {', '.join(ids)}.",
           "meta:",
           f"  title: {json.dumps(title or 'A case with ' + ', '.join(ids), ensure_ascii=False)}"]
    if version:
        out.append(f"  library: {json.dumps(str(version))}")
    out.append("language:")
    out += [templates[k] for k in templates if k in used]          # the library's order
    if issues:
        out += [""] + issues
    out += ["", "argument_schemes:"]
    out += [blocks[sid] + "\n" for sid in ids]
    return "\n".join(out) + CASE


def main(argv):
    args, library, title = [], os.path.join(ROOT, "walton.yml"), None
    it = iter(argv[1:])
    for a in it:
        if a == "--library":
            library = next(it, None)
        elif a == "--title":
            title = next(it, None)
        elif a.startswith("-"):
            print(__doc__.strip(), file=sys.stderr)
            return 2
        else:
            args.append(a)
    if not args or library is None:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    sys.stdout.write(graph(args, library, title))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
